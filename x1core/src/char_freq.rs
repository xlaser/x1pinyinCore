/// 通用规范汉字表一级字（3500 字）基础频率
const COMMON_CHAR_BASE_FREQ_LEVEL1: u32 = 1000;

/// 通用规范汉字表二级字（3000 字）基础频率
const COMMON_CHAR_BASE_FREQ_LEVEL2: u32 = 700;

/// 通用规范汉字表三级字（1605 字）基础频率
const COMMON_CHAR_BASE_FREQ_LEVEL3: u32 = 500;

/// 查询单字的频率值
///
/// 1. 先在精确频率表 `COMMON_CHAR_FREQ` 中查找，取最高值（允许同字多定义）。
/// 2. 未命中则按通用规范汉字表一/二/三级字依次给予递减基础频率，
///    确保规范汉字排在生僻字之前。
/// 3. 完全不在表内的生僻字返回 `None`，由调用方赋默认值。
///
/// 性能：本函数在单字同分 tiebreak 的排序比较器里被高频调用，故用懒构建
/// HashMap（首次 O(736) 构建一次，之后每次 O(1)）；表内无重复字，
/// 仍用 entry-max 保留「同字多定义取最高值」语义。
pub fn char_freq(c: char) -> Option<u32> {
    use std::collections::HashMap;
    use std::sync::OnceLock;
    static FREQ_MAP: OnceLock<HashMap<char, u32>> = OnceLock::new();
    let map = FREQ_MAP.get_or_init(|| {
        let mut m = HashMap::with_capacity(COMMON_CHAR_FREQ.len());
        for &(ch, f) in COMMON_CHAR_FREQ {
            m.entry(ch)
                .and_modify(|v: &mut u32| *v = (*v).max(f))
                .or_insert(f);
        }
        m
    });
    if let Some(&f) = map.get(&c) {
        return Some(f);
    }

    // 2) 通用规范汉字表三级兜底
    if COMMON_CHAR_SET_LEVEL1.binary_search(&c).is_ok() {
        return Some(COMMON_CHAR_BASE_FREQ_LEVEL1);
    }
    if COMMON_CHAR_SET_LEVEL2.binary_search(&c).is_ok() {
        return Some(COMMON_CHAR_BASE_FREQ_LEVEL2);
    }
    if COMMON_CHAR_SET_LEVEL3.binary_search(&c).is_ok() {
        return Some(COMMON_CHAR_BASE_FREQ_LEVEL3);
    }

    None
}

/// 查询双字/多字词的频率值
///
/// 若词不在常用词表中，返回 `None`
pub fn word_freq(s: &str) -> Option<u32> {
    COMMON_WORD_FREQ
        .iter()
        .find(|&&(w, _)| w == s)
        .map(|&(_, f)| f)
}

/// 为词库词条计算综合频率值
///
/// 策略：
/// 1. 若词条在常用词表 → 直接使用该频率（高优先级）
/// 2. 否则基于组成字的频率加权计算
///    - 单字：直接查字频率表，查不到给基础值
///    - 多字：基础值 + 组成字频率之和 / 字数
/// 3. 长度系数：双字词 ×1.5，三字词 ×1.2（鼓励多字词匹配）
/// 词频上限：任何来源的 freq 都不超过此值。
/// 最高单字「的」freq=9999，设 10000 为硬上限，防止虚高频词（历史 50000 bug）。
pub const MAX_FREQ: u32 = 10000;

pub fn compute_freq(simplified: &str) -> u32 {
    // 优先查常用词表（word_freq 表内的值已校验，直接返回）
    if let Some(f) = word_freq(simplified) {
        return f.min(MAX_FREQ);
    }

    let chars: Vec<char> = simplified.chars().collect();
    let char_count = chars.len();

    match char_count {
        1 => {
            // 单字：查频率表，查不到给基础值
            char_freq(chars[0]).unwrap_or(50)
        }
        2 => {
            // 双字词：基础值 + 组成字频率加权平均
            let base = 200u32;
            let avg: u32 = chars
                .iter()
                .map(|&c| char_freq(c).unwrap_or(50))
                .sum::<u32>()
                / 2;
            base + avg / 3 // 缩放，避免超过常用词
        }
        3 => {
            // 三字词：基础值 + 组成字频率加权
            let base = 300u32;
            let avg: u32 = chars
                .iter()
                .map(|&c| char_freq(c).unwrap_or(50))
                .sum::<u32>()
                / 3;
            base + avg / 4
        }
        _ => {
            // 四字+：基础值较低，但仍按字频率加权
            let base = 400u32;
            let avg: u32 = chars
                .iter()
                .map(|&c| char_freq(c).unwrap_or(30))
                .sum::<u32>()
                / char_count as u32;
            base + avg / 5
        }
    }
    .min(MAX_FREQ)
}

