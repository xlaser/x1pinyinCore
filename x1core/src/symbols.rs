/// 快捷触发词 → 符号列表。
///
/// **单一触发词设计**：只有 `/fh`（fh = 符号）一个入口，
/// 所有符号都纳入这一个列表，用户翻页选取，无需记忆多个触发词。
/// 日期时间（/date /time /week）由 Swift 端单独处理，不在此表。
pub const SYMBOL_TABLE: &[(&str, &[&str])] = &[("fh", ALL_SYMBOLS)];

/// 按触发词查符号列表。返回 None 表示无匹配（走正常拼音路径）。
///
/// 精确匹配 key（如 "fh"），不做模糊匹配（避免误触发）。
pub fn lookup_symbols(key: &str) -> Option<&'static [&'static str]> {
    SYMBOL_TABLE
        .iter()
        .find(|(k, _)| *k == key)
        .map(|(_, syms)| *syms)
}

// ===========================================================================
// 测试
