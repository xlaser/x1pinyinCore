#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_lookup_symbols_fh() {
        // 唯一触发词 /fh
        assert_eq!(lookup_symbols("fh"), Some(ALL_SYMBOLS));
    }

    #[test]
    fn test_lookup_symbols_unknown_returns_none() {
        // 旧的分类触发词不再存在（sx/jt/lm 等都合并到 fh）
        assert_eq!(lookup_symbols("sx"), None);
        assert_eq!(lookup_symbols("jt"), None);
        assert_eq!(lookup_symbols("lm"), None);
        assert_eq!(lookup_symbols("xyz"), None);
        assert_eq!(lookup_symbols(""), None);
    }

    #[test]
    fn test_symbol_table_single_trigger() {
        // 守护：只有 1 个触发词（fh），避免又加回多个分类触发词
        assert_eq!(
            SYMBOL_TABLE.len(),
            1,
            "应只有 1 个触发词（fh），实际 {}",
            SYMBOL_TABLE.len()
        );
        assert_eq!(SYMBOL_TABLE[0].0, "fh");
    }

    #[test]
    fn test_all_symbols_non_empty_and_valid() {
        assert!(!ALL_SYMBOLS.is_empty(), "符号列表不应为空");
        for s in ALL_SYMBOLS {
            assert!(!s.is_empty(), "符号项不应为空字符串");
        }
    }

    #[test]
    fn test_all_symbols_count_guard() {
        // 守护：符号总数应 ≥ 300（避免退化）
        assert!(
            ALL_SYMBOLS.len() >= 300,
            "符号总数应 ≥ 300，实际 {}",
            ALL_SYMBOLS.len()
        );
    }

    #[test]
    fn test_all_symbols_contains_high_freq() {
        // 守护：高频标点必须在前 10 个
        let first10 = &ALL_SYMBOLS[..10.min(ALL_SYMBOLS.len())];
        assert!(first10.contains(&"、"), "前10应含「、」");
        assert!(first10.contains(&"，"), "前10应含「，」");
        assert!(first10.contains(&"。"), "前10应含「。」");
    }
}
