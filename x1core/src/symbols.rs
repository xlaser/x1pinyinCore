//! 快捷输入：符号表（/fh 触发，所有符号合并为一组）。
//!
//! 用户输入 `/fh` 时，Swift 端把 `/fh` 送进 buffer，引擎 `try_quick_input`
//! 拦截后返回本模块的符号候选列表。所有符号合并成**单个**列表，按「日常高频
//! → 专业 → 趣味」分层排序，用户只需记住一个触发词 `/fh`（fh = 符号）。
//!
//! 设计原则：
//! - **单一触发词**：不再用 18 个分类触发词（/sx /jt /lm …），避免记忆负担。
//!   所有符号纳入 `/fh`，候选框翻页选取即可。
//! - **分层排序**：常用标点/序号在前，数学/箭头/图形次之，希腊/制表/表情在后。
//!
//! 注：日期时间（/date /time /week）由 Swift 端用 Date+DateFormatter 生成
//! （天然本地时区，零依赖），不走 Rust 符号表。

